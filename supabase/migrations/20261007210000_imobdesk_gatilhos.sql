/** Simula o gatilho (o que está na tela, salvo ou não) num ticket: ✔/✘ por condição, sem gravar nada. */
create or replace function imobdesk.ch_gatilho_simular(p jsonb, p_ticket bigint)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  t imobdesk.ch_tickets;
  v_autor text := coalesce(nullif(p ->> 'autor', ''), 'agente');
begin
  perform imobdesk.ch_gatilho_exigir_admin();
  select * into t from imobdesk.ch_tickets x where x.id = p_ticket and x.excluido_em is null;
  if t.id is null then perform imobdesk.erro('NOT_FOUND', 'Ticket não encontrado.'); end if;
  return jsonb_build_object(
    'ticket', jsonb_build_object('id', t.id, 'assunto', t.assunto),
    'todas', coalesce((select jsonb_agg(jsonb_build_object('condicao', c, 'ok', imobdesk.ch_gatilho_condicao(t, c, v_autor)))
                       from jsonb_array_elements(coalesce(p -> 'todas', '[]')) c), '[]'),
    'qualquer', coalesce((select jsonb_agg(jsonb_build_object('condicao', c, 'ok', imobdesk.ch_gatilho_condicao(t, c, v_autor)))
                          from jsonb_array_elements(coalesce(p -> 'qualquer', '[]')) c), '[]'),
    'executaria', imobdesk.ch_gatilho_atende(t, coalesce(p -> 'todas', '[]'), coalesce(p -> 'qualquer', '[]'), v_autor),
    'jaExecutou', exists (select 1 from imobdesk.ch_gatilho_execucoes e where e.gatilho_id = nullif(p ->> 'id', '')::bigint and e.ticket_id = t.id));
end;
$$;

create or replace function imobdesk.ch_gatilho_execucoes(p_dias int, p_gatilho bigint)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  perform imobdesk.ch_gatilho_exigir_admin();
  return coalesce((
    select jsonb_agg(x order by (x ->> 'criadoEm') desc) from (
      select jsonb_build_object('id', e.id, 'gatilhoId', e.gatilho_id, 'gatilho', g.nome, 'ticketId', e.ticket_id, 'disparo', e.disparo,
                                'resultado', e.resultado, 'detalhe', e.detalhe, 'criadoEm', e.criado_em) x
        from imobdesk.ch_gatilho_execucoes e join imobdesk.ch_gatilhos g on g.id = e.gatilho_id
       where e.criado_em > now() - make_interval(days => greatest(1, least(coalesce(p_dias, 30), 90)))
         and (p_gatilho is null or e.gatilho_id = p_gatilho)
       order by e.criado_em desc limit 300) s), '[]');
end;
$$;

