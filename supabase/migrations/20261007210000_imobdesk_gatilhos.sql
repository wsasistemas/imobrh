create or replace function imobdesk.ch_tickets_gatilho_anotar()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if imobdesk.ch_gatilho_em_execucao() then return null; end if;
  if tg_op = 'INSERT' then
    insert into imobdesk.ch_gatilho_fila (ticket_id, disparo) values (new.id, 'criado');
    return null;
  end if;
  if (new.status_id, new.justificativa_id, new.equipe_id, new.responsavel_id, new.servico_id, new.categoria_id, new.urgencia_id, new.tags, new.cc,
      new.campos, new.assunto, new.solucao_aplicada, new.sla_solucao_ate, new.solicitante_pessoa_id)
     is distinct from
     (old.status_id, old.justificativa_id, old.equipe_id, old.responsavel_id, old.servico_id, old.categoria_id, old.urgencia_id, old.tags, old.cc,
      old.campos, old.assunto, old.solucao_aplicada, old.sla_solucao_ate, old.solicitante_pessoa_id) then
    insert into imobdesk.ch_gatilho_fila (ticket_id, disparo) values (new.id, 'alterado');
  end if;
  if new.status_id is distinct from old.status_id or new.justificativa_id is distinct from old.justificativa_id then
    insert into imobdesk.ch_gatilho_fila (ticket_id, disparo) values (new.id, 'status');
  end if;
  return null;
end;
$$;

