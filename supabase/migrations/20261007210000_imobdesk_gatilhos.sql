-- Administração › Gatilhos (docs/PLANO-gatilhos.md, aprovado em 07/10/2026): automações do ticket por disparo,
-- condições TODAS/QUALQUER e ações, como na Movidesk. Só aditiva.
--
-- Como roda:
--   1. Triggers de linha em ch_tickets e ch_ticket_acoes só ANOTAM o que aconteceu em ch_gatilho_fila.
--   2. Um constraint trigger ADIADO (fim da transação) junta as anotações do ticket e roda os gatilhos uma vez
--      por operação, na ordem da lista, vendo o ticket já com tudo o que o agente salvou.
--   3. Enquanto um gatilho age, a variável de sessão imobdesk.gatilho fica com o nome dele: os triggers
--      não anotam nada (ação de gatilho não dispara gatilho, G2) e o histórico mostra "Gatilho: <nome>".
--   4. Gatilhos de tempo (tempo no status, SLA) rodam pelo pg_cron a cada 5 min (G3).
--   5. Erro de um gatilho fica em ch_gatilho_execucoes e no histórico; nunca desfaz a ação do agente.

-- ---------- Tabelas ----------
create table if not exists imobdesk.ch_gatilhos (
  id             bigint      generated by default as identity primary key,
  nome           text        not null check (length(btrim(nome)) between 2 and 80),
  para           text        not null default 'tickets' check (para in ('tickets')),
  disparos       jsonb       not null default '[]',   -- [{tipo, horas?}]
  todas          jsonb       not null default '[]',   -- [{campo, operador, valores}]
  qualquer       jsonb       not null default '[]',
  acoes          jsonb       not null default '[]',   -- [{tipo, ...valor}]
  execucao       text        not null default 'evento' check (execucao in ('evento', 'ticket')),
  ordem          int         not null default 0,
  ativo          boolean     not null default true,
  atualizado_em  timestamptz not null default now(),
  atualizado_por uuid
);

create table if not exists imobdesk.ch_gatilho_execucoes (
  id         bigint      generated always as identity primary key,
  gatilho_id bigint      not null references imobdesk.ch_gatilhos (id) on delete cascade,
  ticket_id  bigint      not null references imobdesk.ch_tickets (id) on delete cascade,
  chave      text        not null,                 -- evita repetir: 'ev:<fila>', 'ticket', 'tempo:<entrada>', 'slavence:<prazo>'...
  disparo    text        not null,
  resultado  text        not null check (resultado in ('executado', 'erro')),
  detalhe    text,
  criado_em  timestamptz not null default now(),
  unique (gatilho_id, ticket_id, chave)
);
create index if not exists ch_gatilho_execucoes_quando_idx on imobdesk.ch_gatilho_execucoes (criado_em desc);

create table if not exists imobdesk.ch_gatilho_fila (
  id        bigint      generated always as identity primary key,
  ticket_id bigint      not null,
  disparo   text        not null,
  txid      bigint      not null default txid_current(),
  criado_em timestamptz not null default now()
);
create index if not exists ch_gatilho_fila_idx on imobdesk.ch_gatilho_fila (ticket_id, txid);

-- Avisos do sino do portal (G4).
create table if not exists imobdesk.ch_notificacoes (
  id         bigint      generated always as identity primary key,
  usuario_id uuid        not null references imobdesk.usuarios (id) on delete cascade,
  ticket_id  bigint      references imobdesk.ch_tickets (id) on delete cascade,
  titulo     text        not null,
  texto      text        not null default '',
  lida_em    timestamptz,
  criado_em  timestamptz not null default now()
);
create index if not exists ch_notificacoes_usuario_idx on imobdesk.ch_notificacoes (usuario_id, criado_em desc);

do $$
declare
  t text;
begin
  foreach t in array array['ch_gatilhos', 'ch_gatilho_execucoes', 'ch_gatilho_fila', 'ch_notificacoes'] loop
    execute format('alter table imobdesk.%I enable row level security', t);
    execute format('revoke all on imobdesk.%I from anon, public, authenticated', t);
    execute format('grant all on imobdesk.%I to service_role', t);
  end loop;
end;
$$;

-- ---------- Avaliação ----------
/** O setor está no expediente agora? Sem horário cadastrado = sempre. */
create or replace function imobdesk.ch_dentro_expediente(p_setor bigint, p_quando timestamptz)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select case
    when not exists (select 1 from imobdesk.at_horarios x where x.setor_id = p_setor and x.aberto) then true
    else exists (select 1 from imobdesk.at_horarios x
                 where x.setor_id = p_setor and x.aberto
                   and x.dia = extract(dow from (p_quando at time zone 'America/Sao_Paulo'))::int
                   and (p_quando at time zone 'America/Sao_Paulo')::time >= x.abre
                   and (p_quando at time zone 'America/Sao_Paulo')::time < x.fecha) end;
$$;

/**
 * Uma condição de gatilho. Campos: status ("id" ou "id:justificativa"), urgencia, categoria, servico (vale o nó e os
 * de dentro), equipe, responsavel, setor, origem, tags, texto (assunto e conversa), campo:<chave>, horario
 * ("dentro"/"fora" do expediente) e autor (quem fez: solicitante, agente, sistema).
 */
create or replace function imobdesk.ch_gatilho_condicao(t imobdesk.ch_tickets, c jsonb, p_autor text)
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_campo text := c ->> 'campo';
  v_op text := c ->> 'operador';
  v_valores text[] := array(select jsonb_array_elements_text(coalesce(c -> 'valores', '[]')));
  v_atual text[];
begin
  if v_campo in ('servico', 'categoria', 'urgencia', 'setor', 'origem') or v_campo like 'campo:%' then
    if v_op in ('um_de', 'nao_um_de', 'preenchido', 'vazio') then
      return imobdesk.ch_regra_condicao(t, c);
    end if;
  end if;
  v_atual := case v_campo
    when 'status' then array[t.status_id::text, t.status_id::text || ':' || coalesce(t.justificativa_id::text, '')]
    when 'equipe' then array_remove(array[t.equipe_id::text], null)
    when 'responsavel' then array_remove(array[t.responsavel_id::text], null)
    when 'tags' then t.tags
    when 'texto' then array[t.assunto] || array(select a.texto from imobdesk.ch_ticket_acoes a where a.ticket_id = t.id order by a.numero desc limit 3)
    when 'horario' then array[case when imobdesk.ch_dentro_expediente(t.setor_id, now()) then 'dentro' else 'fora' end]
    when 'autor' then array[coalesce(p_autor, 'agente')]
    when 'servico' then array_remove(array[t.servico_id::text], null)
    when 'categoria' then array_remove(array[t.categoria_id::text], null)
    when 'urgencia' then array[t.urgencia_id::text]
    when 'setor' then array[t.setor_id::text]
    when 'origem' then array[t.origem]
    else case when v_campo like 'campo:%' then array_remove(array[nullif(btrim(t.campos ->> substr(v_campo, 7)), '')], null) end
  end;
  if v_atual is null then return false; end if;
  return case v_op
    when 'um_de' then v_atual && v_valores
    when 'nao_um_de' then not (v_atual && v_valores)
    when 'preenchido' then cardinality(v_atual) > 0
    when 'vazio' then cardinality(v_atual) = 0
    when 'contem' then exists (select 1 from unnest(v_atual) a, unnest(v_valores) v where v <> '' and a ilike '%' || v || '%')
    when 'nao_contem' then not exists (select 1 from unnest(v_atual) a, unnest(v_valores) v where v <> '' and a ilike '%' || v || '%')
    else false end;
end;
$$;

/** TODAS valem e (QUALQUER vazia ou pelo menos uma vale). */
create or replace function imobdesk.ch_gatilho_atende(t imobdesk.ch_tickets, p_todas jsonb, p_qualquer jsonb, p_autor text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select not exists (select 1 from jsonb_array_elements(coalesce(p_todas, '[]')) c where not imobdesk.ch_gatilho_condicao(t, c, p_autor))
     and (jsonb_array_length(coalesce(p_qualquer, '[]')) = 0
          or exists (select 1 from jsonb_array_elements(p_qualquer) c where imobdesk.ch_gatilho_condicao(t, c, p_autor)));
$$;

