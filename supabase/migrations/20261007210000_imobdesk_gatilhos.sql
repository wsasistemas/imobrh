/** No fim da transação: junta as anotações do ticket e roda os gatilhos uma vez. */
create or replace function imobdesk.ch_gatilho_fila_processar()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_disp text[];
  v_min bigint;
begin
  with apagados as (
    delete from imobdesk.ch_gatilho_fila f where f.ticket_id = new.ticket_id and f.txid = new.txid returning f.id, f.disparo)
  select array_agg(distinct a.disparo), min(a.id) into v_disp, v_min from apagados a;
  if v_disp is null then return null; end if;
  perform imobdesk.ch_gatilhos_rodar(new.ticket_id, v_disp, 'ev:' || v_min,
            case when 'acao_solicitante' = any (v_disp) then 'solicitante' else 'agente' end);
  return null;
end;
$$;

