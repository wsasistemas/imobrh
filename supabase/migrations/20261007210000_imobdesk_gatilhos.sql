/** Valida e grava. Precisa de pelo menos um disparo e uma ação (como na Movidesk). */
create or replace function imobdesk.ch_gatilho_salvar(p jsonb)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_ator uuid := imobdesk.ch_gatilho_exigir_admin();
  v_id bigint := nullif(p ->> 'id', '')::bigint;
  v_nome text := btrim(coalesce(p ->> 'nome', ''));
  v_disp jsonb := coalesce(p -> 'disparos', '[]');
  v_todas jsonb := coalesce(p -> 'todas', '[]');
  v_qualquer jsonb := coalesce(p -> 'qualquer', '[]');
  v_acoes jsonb := coalesce(p -> 'acoes', '[]');
  v_campos text[] := array['status', 'urgencia', 'categoria', 'servico', 'equipe', 'responsavel', 'setor', 'origem', 'tags', 'texto', 'horario', 'autor'];
begin
  if length(v_nome) not between 2 and 80 then perform imobdesk.erro('INVALID_INPUT', 'Informe o nome do gatilho (2 a 80 letras).', 'nome'); end if;
  if exists (select 1 from imobdesk.ch_gatilhos g where lower(btrim(g.nome)) = lower(v_nome) and g.id is distinct from v_id) then
    perform imobdesk.erro('DUPLICATE', 'Já existe um gatilho com esse nome.', 'nome');
  end if;
  if jsonb_typeof(v_disp) <> 'array' or jsonb_array_length(v_disp) = 0 then
    perform imobdesk.erro('INVALID_INPUT', 'Marque pelo menos um disparo em "Dispara quando".', 'disparos');
  end if;
  if exists (select 1 from jsonb_array_elements(v_disp) d
             where coalesce(d ->> 'tipo', '') not in ('criado', 'alterado', 'status', 'acao_solicitante', 'acao_agente', 'tempo_status', 'sla_vence', 'sla_vencido')
                or ((d ->> 'tipo') in ('tempo_status', 'sla_vence') and coalesce(nullif(d ->> 'horas', '')::numeric, 0) not between 0.25 and 2000)) then
    perform imobdesk.erro('INVALID_INPUT', 'Revise os disparos: as horas precisam estar entre 0,25 e 2000.', 'disparos');
  end if;
  if jsonb_typeof(v_todas) <> 'array' or jsonb_typeof(v_qualquer) <> 'array'
     or exists (select 1 from jsonb_array_elements(v_todas || v_qualquer) c
                where not ((c ->> 'campo') = any (v_campos) or (c ->> 'campo') like 'campo:%')
                   or coalesce(c ->> 'operador', '') not in ('um_de', 'nao_um_de', 'preenchido', 'vazio', 'contem', 'nao_contem')
                   or ((c ->> 'operador') in ('um_de', 'nao_um_de', 'contem', 'nao_contem') and coalesce(jsonb_array_length(c -> 'valores'), 0) = 0)) then
    perform imobdesk.erro('INVALID_INPUT', 'Revise as condições: campo, operador e valores.', 'condicoes');
  end if;
  if jsonb_typeof(v_acoes) <> 'array' or jsonb_array_length(v_acoes) = 0 then
    perform imobdesk.erro('INVALID_INPUT', 'Adicione pelo menos uma ação.', 'acoes');
  end if;
  if exists (select 1 from jsonb_array_elements(v_acoes) a
             where coalesce(a ->> 'tipo', '') not in ('status', 'equipe', 'responsavel', 'urgencia', 'categoria', 'servico', 'tags_adicionar', 'tags_remover',
                                                       'campo', 'solucao', 'nota_interna', 'responder_macro', 'seguidor', 'avisar')
                or (a ->> 'tipo' = 'status' and not exists (select 1 from imobdesk.ch_status s where s.id = nullif(a ->> 'statusId', '')::bigint))
                or (a ->> 'tipo' = 'responder_macro' and not exists (select 1 from imobdesk.ch_macros m where m.id = nullif(a ->> 'macroId', '')::bigint))
                or (a ->> 'tipo' = 'campo' and not exists (select 1 from imobdesk.ch_campos c where c.chave = a ->> 'chave'))
                or (a ->> 'tipo' in ('nota_interna', 'solucao') and length(btrim(coalesce(a ->> 'texto', ''))) = 0)
                or (a ->> 'tipo' in ('tags_adicionar', 'tags_remover') and coalesce(jsonb_array_length(a -> 'tags'), 0) = 0)) then
    perform imobdesk.erro('INVALID_INPUT', 'Revise as ações: falta o valor de alguma delas.', 'acoes');
  end if;

  if v_id is null then
    insert into imobdesk.ch_gatilhos (nome, disparos, todas, qualquer, acoes, execucao, ativo, ordem, atualizado_por)
    values (v_nome, v_disp, v_todas, v_qualquer, v_acoes, coalesce(nullif(p ->> 'execucao', ''), 'evento'), coalesce((p ->> 'ativo')::boolean, true),
            coalesce((select max(ordem) from imobdesk.ch_gatilhos), 0) + 1, v_ator)
    returning id into v_id;
  else
    update imobdesk.ch_gatilhos set nome = v_nome, disparos = v_disp, todas = v_todas, qualquer = v_qualquer, acoes = v_acoes,
           execucao = coalesce(nullif(p ->> 'execucao', ''), execucao), ativo = coalesce((p ->> 'ativo')::boolean, ativo), atualizado_em = now(), atualizado_por = v_ator
     where id = v_id;
    if not found then perform imobdesk.erro('NOT_FOUND', 'Gatilho não encontrado.'); end if;
  end if;
  perform imobdesk.registrar_auditoria(v_ator, 'atendimento', 'update', format('Gatilho "%s" salvo', v_nome), null, p, v_id::text);
  return v_id;
end;
$$;

create or replace function imobdesk.ch_gatilho_ordenar(p_ids bigint[])
returns void
