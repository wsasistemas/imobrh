-- ---------- Disparos por tempo (G3) ----------
/** Chamado pelo pg_cron a cada 5 min: tempo no status, SLA vence em ≤ N h e SLA vencido. */
create or replace function imobdesk.ch_gatilhos_tempo()
returns int
language plpgsql
security definer
set search_path = ''
as $$
declare
  g imobdesk.ch_gatilhos;
  d jsonb;
  r record;
  v_horas numeric;
  v_n int := 0;
begin
  for g in select * from imobdesk.ch_gatilhos x
            where x.ativo and exists (select 1 from jsonb_array_elements(x.disparos) y where y ->> 'tipo' in ('tempo_status', 'sla_vence', 'sla_vencido'))
            order by x.ordem, x.id loop
    for d in select * from jsonb_array_elements(g.disparos) loop
      v_horas := nullif(d ->> 'horas', '')::numeric;
      if d ->> 'tipo' = 'tempo_status' and v_horas > 0 then
        for r in
          select t.id, coalesce((select max(e.criado_em) from imobdesk.ch_ticket_eventos e where e.ticket_id = t.id and e.tipo = 'status'), t.criado_em) as entrada, t.setor_id
            from imobdesk.ch_tickets t
           where t.encerrado_em is null and t.excluido_em is null and t.mesclado_em_id is null
        loop
          if imobdesk.ch_somar_horas_uteis(r.setor_id, r.entrada, v_horas) <= now() then
            if imobdesk.ch_gatilho_executar(g, r.id, 'tempo:' || extract(epoch from r.entrada)::bigint, 'tempo_status', 'sistema') then v_n := v_n + 1; end if;
          end if;
        end loop;
      elsif d ->> 'tipo' = 'sla_vence' and v_horas > 0 then
        for r in
          select t.id, t.sla_solucao_ate from imobdesk.ch_tickets t
           where t.encerrado_em is null and t.excluido_em is null and t.mesclado_em_id is null and t.sla_pausado_desde is null
             and t.sla_solucao_ate > now() and t.sla_solucao_ate <= now() + make_interval(secs => (v_horas * 3600)::int)
        loop
          if imobdesk.ch_gatilho_executar(g, r.id, 'slavence:' || extract(epoch from r.sla_solucao_ate)::bigint, 'sla_vence', 'sistema') then v_n := v_n + 1; end if;
        end loop;
      elsif d ->> 'tipo' = 'sla_vencido' then
        for r in
          select t.id, t.sla_solucao_ate from imobdesk.ch_tickets t
           where t.encerrado_em is null and t.excluido_em is null and t.mesclado_em_id is null and t.sla_pausado_desde is null
             and t.sla_solucao_ate <= now()
        loop
          if imobdesk.ch_gatilho_executar(g, r.id, 'slavencido:' || extract(epoch from r.sla_solucao_ate)::bigint, 'sla_vencido', 'sistema') then v_n := v_n + 1; end if;
        end loop;
      end if;
    end loop;
  end loop;
  -- Anotações órfãs (transação que caiu) não ficam para sempre.
  delete from imobdesk.ch_gatilho_fila f where f.criado_em < now() - interval '1 hour';
  return v_n;
end;
$$;

