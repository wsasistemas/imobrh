  tipo             text        not null check (tipo in ('publica', 'interna')),
  canal            text        not null check (canal in ('email', 'whatsapp', 'portal')),
  direcao          text        not null default 'saida' check (direcao in ('entrada', 'saida')),         -- entrada = veio do solicitante
  autor_id         uuid        references imobdesk.usuarios (id) on delete set null,
  autor_nome       text        not null,
  texto            text        not null default '' check (length(texto) <= 100000),
  html             text,
  anexos           jsonb       not null default '[]',
  envio_status     text        check (envio_status in ('pendente', 'enviado', 'falhou', 'nao_se_aplica')),
  envio_erro       text,
  email_message_id text,
  mensagem_id      bigint,                                                                               -- at_mensagens (WhatsApp)
  criado_em        timestamptz not null default now(),
  unique (ticket_id, numero)
