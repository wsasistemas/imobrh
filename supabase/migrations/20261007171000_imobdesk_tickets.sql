/** Cria ticket pelo portal (agente ou intranet). Canais e-mail e WhatsApp criam pelas Edge Functions. */
create or replace function imobdesk.ch_ticket_criar(p jsonb)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_ator uuid := (select auth.uid());
  v_servico bigint := nullif(p ->> 'servicoId', '')::bigint;
  v_setor bigint := nullif(p ->> 'setorId', '')::bigint;
  v_id bigint;
  v_pessoa bigint := nullif(p ->> 'solicitantePessoaId', '')::bigint;
  v_nome text := btrim(coalesce(p ->> 'solicitanteNome', ''));
  v_contato text;
  v_texto text := coalesce(p ->> 'descricao', '');
begin
  if not (imobdesk.ch_eh_admin() or imobdesk.tem_permissao('gestao_chamados_tickets')) then
    perform imobdesk.erro('FORBIDDEN', 'Sem acesso para abrir tickets.');
  end if;
  if length(btrim(coalesce(p ->> 'assunto', ''))) = 0 then perform imobdesk.erro('INVALID_INPUT', 'Informe o assunto.', 'assunto'); end if;
  if length(btrim(v_texto)) = 0 then perform imobdesk.erro('INVALID_INPUT', 'Descreva a solicitação.', 'descricao'); end if;
  if v_servico is not null then
    select s.setor_id into v_setor from imobdesk.ch_servicos s where s.id = v_servico and s.ativo;
    if v_setor is null then perform imobdesk.erro('INVALID_INPUT', 'Serviço inválido.', 'servicoId'); end if;
  end if;
  if v_setor is null or not exists (select 1 from imobdesk.at_setores s where s.id = v_setor and s.ativo) then
    perform imobdesk.erro('INVALID_INPUT', 'Escolha o serviço ou o setor.', 'servicoId');
  end if;
  if v_pessoa is not null then
    select pe.nome, (select c.valor from imobdesk.at_pessoa_contatos c where c.pessoa_id = pe.id and c.tipo = 'email' order by c.principal desc limit 1)
      into v_nome, v_contato from imobdesk.at_pessoas pe where pe.id = v_pessoa;
  end if;
  if length(coalesce(v_nome, '')) = 0 then perform imobdesk.erro('INVALID_INPUT', 'Informe o solicitante.', 'solicitante'); end if;

  insert into imobdesk.ch_tickets (assunto, origem, recebido_em, solicitante_pessoa_id, solicitante_nome, solicitante_contato, setor_id, servico_id,
                                             categoria_id, urgencia_id, status_id, equipe_id, responsavel_id, tags, cc, campos, criado_por)
  values (btrim(p ->> 'assunto'), coalesce(nullif(p ->> 'origem', ''), 'agente'), case when p ->> 'origem' = 'intranet' then 'Intranet' else 'Agente' end,
          v_pessoa, v_nome, coalesce(v_contato, nullif(btrim(p ->> 'solicitanteContato'), '')), v_setor, v_servico,
          coalesce(nullif(p ->> 'categoriaId', '')::bigint, (select s.categoria_padrao_id from imobdesk.ch_servicos s where s.id = v_servico), (select c.id from imobdesk.ch_categorias c where c.padrao)),
          coalesce(nullif(p ->> 'urgenciaId', '')::bigint, (select s.urgencia_padrao_id from imobdesk.ch_servicos s where s.id = v_servico), (select u.id from imobdesk.ch_urgencias u where u.padrao)),
          coalesce((select s.id from imobdesk.ch_status s where s.categoria = 'novo' and s.ativo order by s.ordem limit 1), 1),
          nullif(p ->> 'equipeId', '')::bigint, nullif(p ->> 'responsavelId', '')::uuid,
          coalesce(array(select jsonb_array_elements_text(p -> 'tags')), '{}'), coalesce(array(select jsonb_array_elements_text(p -> 'cc')), '{}'),
          coalesce(p -> 'campos', '{}'), v_ator)
  returning id into v_id;

  insert into imobdesk.ch_ticket_acoes (ticket_id, numero, tipo, canal, direcao, autor_id, autor_nome, texto, envio_status)
  values (v_id, 1, 'publica', 'portal', 'entrada', v_ator, imobdesk.ch_nome_usuario(v_ator), v_texto, 'nao_se_aplica');
  return v_id;
end;
$$;

/**
 * Altera o ticket. Só as chaves enviadas mudam. Resolver ou fechar exige os campos obrigatórios e a
 * "Solução aplicada" (plano de IA, D2). Alterar o prazo à mão: gestor do setor, Admin ou Super admin, com justificativa.
 */
create or replace function imobdesk.ch_ticket_atualizar(p_id bigint, p jsonb)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  t imobdesk.ch_tickets := imobdesk.ch_ticket_visivel(p_id);
  n imobdesk.ch_tickets;
  v_cat text;
  v_pend text[];
begin
  if t.excluido_em is not null then perform imobdesk.erro('INVALID_INPUT', 'Ticket excluído.'); end if;
  if t.mesclado_em_id is not null then perform imobdesk.erro('INVALID_INPUT', format('Este ticket foi mesclado em #%s.', t.mesclado_em_id)); end if;
  n := t;
  if p ? 'servicoId' then n.servico_id := nullif(p ->> 'servicoId', '')::bigint;
    if n.servico_id is not null then
      n.setor_id := (select s.setor_id from imobdesk.ch_servicos s where s.id = n.servico_id and s.ativo);
      if n.setor_id is null then perform imobdesk.erro('INVALID_INPUT', 'Serviço inválido.', 'servicoId'); end if;
      if not (p ? 'equipeId') then n.equipe_id := null; end if;   -- o gatilho põe a equipe do serviço
    end if;
  end if;
  if p ? 'categoriaId' then n.categoria_id := nullif(p ->> 'categoriaId', '')::bigint; end if;
  if p ? 'urgenciaId' then n.urgencia_id := coalesce(nullif(p ->> 'urgenciaId', '')::bigint, n.urgencia_id); end if;
  if p ? 'equipeId' then n.equipe_id := nullif(p ->> 'equipeId', '')::bigint; end if;
  if p ? 'responsavelId' then n.responsavel_id := nullif(p ->> 'responsavelId', '')::uuid; end if;
  if p ? 'statusId' then n.status_id := (p ->> 'statusId')::bigint; n.justificativa_id := nullif(p ->> 'justificativaId', '')::bigint; end if;
  if p ? 'tags' then n.tags := coalesce(array(select distinct btrim(x) from jsonb_array_elements_text(p -> 'tags') x where btrim(x) <> ''), '{}'); end if;
  if p ? 'cc' then n.cc := coalesce(array(select distinct lower(btrim(x)) from jsonb_array_elements_text(p -> 'cc') x where btrim(x) <> ''), '{}'); end if;
  if p ? 'campos' then n.campos := t.campos || coalesce(p -> 'campos', '{}'); end if;
  if p ? 'assunto' and length(btrim(p ->> 'assunto')) > 0 then n.assunto := btrim(p ->> 'assunto'); end if;
  if p ? 'solucaoAplicada' then n.solucao_aplicada := nullif(btrim(p ->> 'solucaoAplicada'), ''); end if;
  if p ? 'solicitantePessoaId' then
    n.solicitante_pessoa_id := nullif(p ->> 'solicitantePessoaId', '')::bigint;
    select pe.nome into n.solicitante_nome from imobdesk.at_pessoas pe where pe.id = n.solicitante_pessoa_id;
    if n.solicitante_nome is null then perform imobdesk.erro('INVALID_INPUT', 'Solicitante não encontrado.', 'solicitante'); end if;
  end if;
  if p ? 'slaSolucaoAte' then
    if not (imobdesk.ch_eh_admin() or imobdesk.at_gestor_de(t.setor_id)) then
      perform imobdesk.erro('FORBIDDEN', 'Só o gestor do setor, Admin ou Super admin alteram o prazo.');
    end if;
    if length(btrim(coalesce(p ->> 'slaJustificativa', ''))) < 5 then perform imobdesk.erro('INVALID_INPUT', 'Explique por que o prazo mudou.', 'slaJustificativa'); end if;
    n.sla_solucao_ate := (p ->> 'slaSolucaoAte')::timestamptz;
    n.sla_manual := true;
  end if;

  v_cat := (select s.categoria from imobdesk.ch_status s where s.id = n.status_id and s.ativo);
  if v_cat is null then perform imobdesk.erro('INVALID_INPUT', 'Status inválido.', 'statusId'); end if;
  if v_cat in ('resolvido', 'fechado') then
    v_pend := imobdesk.ch_campos_pendentes(n);
    if cardinality(v_pend) > 0 then
      perform imobdesk.erro('INVALID_INPUT', 'Preencha antes de resolver: ' || array_to_string(v_pend, ', ') || '.', 'campos');
    end if;
    if n.servico_id is null then perform imobdesk.erro('INVALID_INPUT', 'Escolha o serviço antes de resolver.', 'servicoId'); end if;
    if n.solucao_aplicada is null then perform imobdesk.erro('INVALID_INPUT', 'Descreva a solução aplicada antes de resolver.', 'solucaoAplicada'); end if;
  end if;

  update imobdesk.ch_tickets set
    servico_id = n.servico_id, setor_id = n.setor_id, categoria_id = n.categoria_id, urgencia_id = n.urgencia_id, equipe_id = n.equipe_id,
    responsavel_id = n.responsavel_id, status_id = n.status_id, justificativa_id = n.justificativa_id, tags = n.tags, cc = n.cc, campos = n.campos,
    assunto = n.assunto, solucao_aplicada = n.solucao_aplicada, solicitante_pessoa_id = n.solicitante_pessoa_id, solicitante_nome = n.solicitante_nome,
    sla_solucao_ate = n.sla_solucao_ate, sla_manual = n.sla_manual
  where id = p_id;

  if p ? 'slaSolucaoAte' then
    insert into imobdesk.ch_ticket_eventos (ticket_id, tipo, descricao, autor_id, autor_nome)
    values (p_id, 'sla_justificativa', 'Motivo: ' || btrim(p ->> 'slaJustificativa'), (select auth.uid()), imobdesk.ch_nome_usuario((select auth.uid())));
  end if;
end;
$$;

/**
 * Adiciona uma ação: pública (resposta ao solicitante pelo canal do ticket) ou nota interna. A resposta pública
 * entra como "pendente" de envio; o envio por e-mail e WhatsApp é da Etapa 4 (Edge Functions).
 * Opcional: statusDepois {statusId, justificativaId} e as mesmas chaves de ch_ticket_atualizar em "campos".
 */
create or replace function imobdesk.ch_ticket_acao(p_id bigint, p jsonb)
returns int
language plpgsql
security definer
set search_path = ''
as $$
declare
  t imobdesk.ch_tickets := imobdesk.ch_ticket_visivel(p_id);
  v_tipo text := coalesce(p ->> 'tipo', 'publica');
  v_texto text := coalesce(p ->> 'texto', '');
  v_num int;
  v_canal text;
  v_ator uuid := (select auth.uid());
begin
  if t.excluido_em is not null or t.mesclado_em_id is not null then perform imobdesk.erro('INVALID_INPUT', 'Este ticket não recebe mais ações.'); end if;
  if v_tipo not in ('publica', 'interna') then perform imobdesk.erro('INVALID_INPUT', 'Tipo de ação inválido.', 'tipo'); end if;
  if length(btrim(v_texto)) = 0 then perform imobdesk.erro('INVALID_INPUT', 'Escreva o texto da ação.', 'texto'); end if;
  v_canal := case when v_tipo = 'interna' then 'portal' when t.origem in ('email', 'whatsapp') then t.origem else 'portal' end;
  perform 1 from imobdesk.ch_tickets x where x.id = p_id for update;
  v_num := coalesce((select max(a.numero) from imobdesk.ch_ticket_acoes a where a.ticket_id = p_id), 0) + 1;
  insert into imobdesk.ch_ticket_acoes (ticket_id, numero, tipo, canal, direcao, autor_id, autor_nome, texto, html, anexos, envio_status)
  values (p_id, v_num, v_tipo, v_canal, 'saida', v_ator, imobdesk.ch_nome_usuario(v_ator), v_texto, p ->> 'html', coalesce(p -> 'anexos', '[]'),
          case when v_tipo = 'publica' and v_canal in ('email', 'whatsapp') then 'pendente' else 'nao_se_aplica' end);
  if v_tipo = 'publica' and t.primeira_resposta_em is null then
    update imobdesk.ch_tickets set primeira_resposta_em = now() where id = p_id;
  end if;
  if jsonb_typeof(p -> 'campos') = 'object' or jsonb_typeof(p -> 'statusDepois') = 'object' then
    perform imobdesk.ch_ticket_atualizar(p_id, coalesce(p -> 'campos', '{}') || coalesce(p -> 'statusDepois', '{}'));
  end if;
  return v_num;
end;
$$;

