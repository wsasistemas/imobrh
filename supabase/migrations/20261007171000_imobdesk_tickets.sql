/** Clonar (T6): ticket novo com os campos; opcionalmente as ações. */
create or replace function imobdesk.ch_ticket_clonar(p_id bigint, p jsonb)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  t imobdesk.ch_tickets := imobdesk.ch_ticket_visivel(p_id);
  v_novo bigint;
  v_ator uuid := (select auth.uid());
begin
  insert into imobdesk.ch_tickets (assunto, origem, recebido_em, solicitante_pessoa_id, solicitante_nome, solicitante_contato, email_conta_id, setor_id,
                                             servico_id, categoria_id, urgencia_id, status_id, tags, cc, campos, clonado_de_id, criado_por)
  select t.assunto, t.origem, t.recebido_em,
         coalesce(nullif(p ->> 'solicitantePessoaId', '')::bigint, t.solicitante_pessoa_id), t.solicitante_nome, t.solicitante_contato, t.email_conta_id,
         t.setor_id, coalesce(nullif(p ->> 'servicoId', '')::bigint, t.servico_id),
         case when coalesce((p ->> 'copiarCampos')::boolean, true) then t.categoria_id end, t.urgencia_id,
         coalesce((select s.id from imobdesk.ch_status s where s.categoria = 'novo' and s.ativo order by s.ordem limit 1), 1),
         case when coalesce((p ->> 'copiarCampos')::boolean, true) then t.tags else '{}' end, t.cc,
         case when coalesce((p ->> 'copiarCampos')::boolean, true) then t.campos else '{}' end, t.id, v_ator
  returning id into v_novo;
  if nullif(p ->> 'servicoId', '') is not null then
    update imobdesk.ch_tickets n set setor_id = s.setor_id from imobdesk.ch_servicos s where n.id = v_novo and s.id = n.servico_id;
  end if;
  if coalesce((p ->> 'copiarAcoes')::boolean, false) then
    insert into imobdesk.ch_ticket_acoes (ticket_id, numero, tipo, canal, direcao, autor_id, autor_nome, texto, html, anexos, envio_status, criado_em)
    select v_novo, a.numero, a.tipo, a.canal, a.direcao, a.autor_id, a.autor_nome, a.texto, a.html, a.anexos, 'nao_se_aplica', a.criado_em
    from imobdesk.ch_ticket_acoes a where a.ticket_id = t.id;
  else
    insert into imobdesk.ch_ticket_acoes (ticket_id, numero, tipo, canal, direcao, autor_id, autor_nome, texto, envio_status)
    values (v_novo, 1, 'interna', 'portal', 'saida', v_ator, imobdesk.ch_nome_usuario(v_ator), format('Clonado do ticket #%s.', t.id), 'nao_se_aplica');
  end if;
  insert into imobdesk.ch_ticket_eventos (ticket_id, tipo, descricao, autor_id, autor_nome)
  values (t.id, 'clonado', format('Clonado para #%s', v_novo), v_ator, imobdesk.ch_nome_usuario(v_ator));
  return v_novo;
end;
$$;

/** Mesclar (T7): as ações vão para o destino; a origem fica Cancelado com "mesclado em". */
create or replace function imobdesk.ch_ticket_mesclar(p_origem bigint, p_destino bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  o imobdesk.ch_tickets := imobdesk.ch_ticket_visivel(p_origem);
  d imobdesk.ch_tickets := imobdesk.ch_ticket_visivel(p_destino);
  v_base int;
  v_ator uuid := (select auth.uid());
  v_cancelado bigint := (select s.id from imobdesk.ch_status s where s.categoria = 'cancelado' and s.ativo order by s.ordem limit 1);
begin
  if p_origem = p_destino then perform imobdesk.erro('INVALID_INPUT', 'Escolha outro ticket como destino.', 'destino'); end if;
  if o.mesclado_em_id is not null or d.mesclado_em_id is not null or o.excluido_em is not null or d.excluido_em is not null then
    perform imobdesk.erro('INVALID_INPUT', 'Um dos tickets já foi mesclado ou excluído.');
  end if;
  perform 1 from imobdesk.ch_tickets x where x.id in (p_origem, p_destino) order by x.id for update;
  v_base := coalesce((select max(a.numero) from imobdesk.ch_ticket_acoes a where a.ticket_id = p_destino), 0);
  update imobdesk.ch_ticket_acoes a set ticket_id = p_destino, numero = v_base + a.numero where a.ticket_id = p_origem;
  update imobdesk.ch_tickets set cc = (select coalesce(array_agg(distinct x), '{}') from unnest(d.cc || o.cc ||
           case when o.solicitante_contato is not null and o.solicitante_contato is distinct from d.solicitante_contato then array[o.solicitante_contato] else '{}'::text[] end) x)
   where id = p_destino;
  -- Conversas e e-mails que apontavam para a origem passam a cair no destino (Etapa 4 usa estes vínculos).
  update imobdesk.ch_tickets set mesclado_em_id = p_destino, status_id = coalesce(v_cancelado, status_id), justificativa_id = null where id = p_origem;
  insert into imobdesk.ch_ticket_acoes (ticket_id, numero, tipo, canal, direcao, autor_id, autor_nome, texto, envio_status)
  values (p_destino, (select max(a.numero) from imobdesk.ch_ticket_acoes a where a.ticket_id = p_destino) + 1,
          'interna', 'portal', 'saida', v_ator, imobdesk.ch_nome_usuario(v_ator), format('Ticket #%s mesclado neste ticket.', p_origem), 'nao_se_aplica');
  insert into imobdesk.ch_ticket_eventos (ticket_id, tipo, descricao, autor_id, autor_nome) values
    (p_origem, 'mesclado', format('Mesclado em #%s', p_destino), v_ator, imobdesk.ch_nome_usuario(v_ator)),
    (p_destino, 'mesclado', format('Recebeu as ações de #%s', p_origem), v_ator, imobdesk.ch_nome_usuario(v_ator));
end;
$$;

/** Excluir (T8): só Super admin, exclusão lógica. */
create or replace function imobdesk.ch_ticket_excluir(p_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_ator uuid := imobdesk.ch_exigir_super();
begin
  update imobdesk.ch_tickets set excluido_em = now(), excluido_por = v_ator where id = p_id and excluido_em is null;
  if not found then perform imobdesk.erro('NOT_FOUND', 'Ticket não encontrado.'); end if;
  insert into imobdesk.ch_ticket_eventos (ticket_id, tipo, descricao, autor_id, autor_nome)
  values (p_id, 'excluido', 'Ticket excluído', v_ator, imobdesk.ch_nome_usuario(v_ator));
  perform imobdesk.registrar_auditoria(v_ator, 'atendimento', 'delete', format('Ticket #%s excluído', p_id), null, null, p_id::text);
end;
$$;

/**
 * Painel (rpc_dashboard): o mesmo formato de src/features/dashboard/types.ts. Tickets visíveis para o usuário:
 * abertos e os encerrados nos últimos 30 dias.
 */
create or replace function imobdesk.ch_painel()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_eu uuid := (select auth.uid());
  v_admin boolean := imobdesk.ch_eh_admin() or imobdesk.at_supervisor();
  v_agora timestamptz := now();
  v_tokens text[] := array['--ds-team-sistemas', '--ds-team-infra', '--ds-ai', '--ds-triage-ai', '--ds-warning', '--ds-success'];
begin
  if not (imobdesk.ch_eh_admin() or imobdesk.tem_permissao('gestao_chamados_visao_geral') or imobdesk.tem_permissao('gestao_chamados_tickets')) then
    perform imobdesk.erro('FORBIDDEN', 'Sem acesso à Gestão de Chamados.');
  end if;
  return (
    with vis as (
      select t.* from imobdesk.ch_tickets t
      where t.excluido_em is null and t.mesclado_em_id is null
        and (t.encerrado_em is null or t.encerrado_em >= v_agora - interval '30 days')
        and imobdesk.ch_pode_ver_ticket(t.setor_id, t.equipe_id, t.responsavel_id)
    ), eq as (
      select e.id, e.nome, row_number() over (order by e.nome) as n from imobdesk.at_equipes e where e.ativa
    )
    select jsonb_build_object(
      'generated_at', v_agora,
      'current_user', jsonb_build_object('id', v_eu, 'name', imobdesk.ch_nome_usuario(v_eu),
                        'initials', imobdesk.ch_iniciais(imobdesk.ch_nome_usuario(v_eu))),
      'my_teams', coalesce((select jsonb_agg(e.nome order by e.nome) from eq e
                            where v_admin or exists (select 1 from imobdesk.at_equipe_membros m where m.equipe_id = e.id and m.usuario_id = v_eu)), '[]'),
      'teams', coalesce((select jsonb_agg(jsonb_build_object('name', e.nome, 'color_token', v_tokens[1 + ((e.n - 1) % 6)]) order by e.nome) from eq e), '[]'),
      'services', coalesce((select jsonb_agg(jsonb_build_object('id', s.id, 'name', s.nome,
                              'team', coalesce((select e.nome from imobdesk.at_equipes e where e.id = imobdesk.ch_servico_equipe(s.id)), ''),
                              'sla_hours', coalesce((select h.solucao from imobdesk.ch_sla_horas(s.id, (select u.id from imobdesk.ch_urgencias u where u.padrao), s.setor_id) h), 0)) order by s.nome)
                            from imobdesk.ch_servicos s where s.ativo and not exists (select 1 from imobdesk.ch_servicos f where f.pai_id = s.id)), '[]'),
      'tickets', coalesce((select jsonb_agg(jsonb_build_object(
          'id', t.id, 'subject', t.assunto, 'requester', t.solicitante_nome,
          'description', coalesce((select a.texto from imobdesk.ch_ticket_acoes a where a.ticket_id = t.id order by a.numero limit 1), ''),
          'service_id', t.servico_id,
          'team', coalesce((select e.nome from imobdesk.at_equipes e where e.id = t.equipe_id), ''),
          'origin', case t.origem when 'email' then 'E-mail' when 'whatsapp' then 'WhatsApp' when 'intranet' then 'Intranet' else 'Agente' end,
          'owner', case when t.responsavel_id is null then null else jsonb_build_object('id', t.responsavel_id, 'name', imobdesk.ch_nome_usuario(t.responsavel_id),
                     'initials', imobdesk.ch_iniciais(imobdesk.ch_nome_usuario(t.responsavel_id))) end,
          'status_id', t.status_id, 'status', st.nome, 'status_categoria', st.categoria,
          'justificativa_id', t.justificativa_id, 'justificativa', (select j.nome from imobdesk.ch_status_justificativas j where j.id = t.justificativa_id),
          'prioridade', (select u.nome from imobdesk.ch_urgencias u where u.id = t.urgencia_id),
          'tags', to_jsonb(t.tags), 'recebido_em', t.recebido_em, 'criado_em', t.criado_em,
          'sla_due_minutes', coalesce(round(extract(epoch from (t.sla_solucao_ate - coalesce(t.sla_pausado_desde, v_agora))) / 60), 0),
          'opened_today', (t.criado_em at time zone 'America/Sao_Paulo')::date = (v_agora at time zone 'America/Sao_Paulo')::date,
          'closed_at', t.encerrado_em) order by t.id)
        from vis t join imobdesk.ch_status st on st.id = t.status_id), '[]'),
      'triage', jsonb_build_object('period', 'Hoje', 'automatic', 0, 'total',
                  (select count(*) from vis t where (t.criado_em at time zone 'America/Sao_Paulo')::date = (v_agora at time zone 'America/Sao_Paulo')::date),
                  'by_intranet_form', 0, 'by_email_rule', 0, 'by_ai', 0, 'manual', 0, 'pending_review', 0),
      'sla_health', jsonb_build_object('period', '7 dias',
                  'first_response_percent', coalesce((select round(100.0 * count(*) filter (where t.primeira_resposta_em <= t.sla_resposta_ate) / nullif(count(*), 0))
                                                      from vis t where t.primeira_resposta_em >= v_agora - interval '7 days'), 100),
                  'resolution_percent', coalesce((select round(100.0 * count(*) filter (where t.encerrado_em <= t.sla_solucao_ate) / nullif(count(*), 0))
                                                  from vis t join imobdesk.ch_status st on st.id = t.status_id
                                                  where st.categoria in ('resolvido', 'fechado') and t.encerrado_em >= v_agora - interval '7 days'), 100)),
      'inbound', (select jsonb_agg(jsonb_build_object('hour', h,
                     'today', (select count(*) from vis t where (t.criado_em at time zone 'America/Sao_Paulo')::date = (v_agora at time zone 'America/Sao_Paulo')::date
                                 and extract(hour from t.criado_em at time zone 'America/Sao_Paulo') = h),
                     'yesterday', (select count(*) from vis t where (t.criado_em at time zone 'America/Sao_Paulo')::date = (v_agora at time zone 'America/Sao_Paulo')::date - 1
                                 and extract(hour from t.criado_em at time zone 'America/Sao_Paulo') = h)) order by h)
                  from generate_series(8, 18) h)
    )
  );
end;
$$;

do $$
