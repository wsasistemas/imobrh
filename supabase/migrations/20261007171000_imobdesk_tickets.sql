-- ---------- Prazo em horas úteis (D6) ----------
/**
 * Soma horas úteis a partir de um instante, no horário do setor (at_horarios, fuso de São Paulo).
 * Setor sem horário cadastrado = horas corridas.
 */
create or replace function imobdesk.ch_somar_horas_uteis(p_setor bigint, p_inicio timestamptz, p_horas numeric)
returns timestamptz
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_restante numeric := p_horas * 60;   -- minutos
  v_cursor timestamp := (p_inicio at time zone 'America/Sao_Paulo');
  v_dia date;
  h record;
  v_ini timestamp;
  v_fim timestamp;
  v_disp numeric;
  i int := 0;
begin
  if p_horas is null or p_inicio is null then return null; end if;
  if not exists (select 1 from imobdesk.at_horarios x where x.setor_id = p_setor and x.aberto) then
    return p_inicio + make_interval(mins => round(v_restante)::int);
  end if;
  loop
    i := i + 1;
    exit when i > 800;
    v_dia := v_cursor::date;
    select x.aberto, x.abre, x.fecha into h from imobdesk.at_horarios x where x.setor_id = p_setor and x.dia = extract(dow from v_dia)::int;
    if found and h.aberto then
      v_ini := greatest(v_cursor, v_dia + h.abre);
      v_fim := v_dia + h.fecha;
      if v_ini < v_fim then
        v_disp := extract(epoch from (v_fim - v_ini)) / 60;
        if v_restante <= v_disp then
          return (v_ini + make_interval(mins => round(v_restante)::int)) at time zone 'America/Sao_Paulo';
        end if;
        v_restante := v_restante - v_disp;
      end if;
    end if;
    v_cursor := (v_dia + 1)::timestamp;
  end loop;
  return null;
end;
$$;

/** Horas de 1ª resposta e de solução: serviço × urgência (subindo pelos pais); sem prazo, o SLA padrão do setor. */
create or replace function imobdesk.ch_sla_horas(p_servico bigint, p_urgencia bigint, p_setor bigint)
returns table (resposta numeric, solucao numeric)
language sql
stable
security definer
set search_path = ''
as $$
  with recursive cadeia as (
    select s.id, s.pai_id, 0 as prof from imobdesk.ch_servicos s where s.id = p_servico
    union all
    select s.id, s.pai_id, c.prof + 1 from imobdesk.ch_servicos s join cadeia c on s.id = c.pai_id
  ), achado as (
    select l.resposta_horas, l.solucao_horas from cadeia c
    join imobdesk.ch_servicos_sla l on l.servico_id = c.id and l.urgencia_id = p_urgencia
    order by c.prof limit 1
  )
  select coalesce((select a.resposta_horas from achado a), (select st.sla_padrao_horas / 2 from imobdesk.at_setores st where st.id = p_setor)),
         coalesce((select a.solucao_horas from achado a), (select st.sla_padrao_horas from imobdesk.at_setores st where st.id = p_setor));
$$;

/** Equipe do serviço (o próprio ou o pai mais próximo que tenha equipe). */
create or replace function imobdesk.ch_servico_equipe(p_servico bigint)
returns bigint
language sql
stable
security definer
set search_path = ''
as $$
  with recursive cadeia as (
    select s.id, s.pai_id, s.equipe_id, 0 as prof from imobdesk.ch_servicos s where s.id = p_servico
    union all
    select s.id, s.pai_id, s.equipe_id, c.prof + 1 from imobdesk.ch_servicos s join cadeia c on s.id = c.pai_id
  )
  select c.equipe_id from cadeia c where c.equipe_id is not null order by c.prof limit 1;
$$;

-- ---------- Visibilidade (D7) ----------
create or replace function imobdesk.ch_pode_ver_ticket(p_setor bigint, p_equipe bigint, p_responsavel uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  -- coalesce: com responsável vazio a comparação daria NULL, e "not NULL" deixaria passar (achado no ensaio).
  select coalesce(
         imobdesk.ch_eh_admin()
      or imobdesk.at_supervisor()
      or p_responsavel = (select auth.uid())
      or imobdesk.at_gestor_de(p_setor)
      or (imobdesk.tem_permissao('gestao_chamados_tickets')
          and ((p_equipe is not null and exists (select 1 from imobdesk.at_equipe_membros m where m.equipe_id = p_equipe and m.usuario_id = (select auth.uid())))
               or exists (select 1 from imobdesk.at_equipe_membros m join imobdesk.at_equipes e on e.id = m.equipe_id
                          where m.usuario_id = (select auth.uid()) and e.setor_id = p_setor and p_equipe is null)
               or imobdesk.at_membro_de(p_setor))), false);
$$;

create or replace function imobdesk.ch_ticket_visivel(p_id bigint)
returns imobdesk.ch_tickets
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  t imobdesk.ch_tickets;
begin
  select * into t from imobdesk.ch_tickets x where x.id = p_id and (x.excluido_em is null or imobdesk.eh_super_admin());
  if t.id is null or not imobdesk.ch_pode_ver_ticket(t.setor_id, t.equipe_id, t.responsavel_id) then
    perform imobdesk.erro('NOT_FOUND', 'Ticket não encontrado.');
  end if;
  return t;
end;
$$;

-- ---------- Regras para exibição no banco ----------
/** O ticket atende a esta condição de regra? */
create or replace function imobdesk.ch_regra_condicao(t imobdesk.ch_tickets, c jsonb)
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_campo text := c ->> 'campo';
  v_op text := c ->> 'operador';
  v_valores text[] := array(select jsonb_array_elements_text(coalesce(c -> 'valores', '[]')));
  v_atual text[];
begin
  if v_campo = 'servico' then
    -- O serviço do ticket ou qualquer serviço acima dele.
    with recursive cadeia as (
      select s.id, s.pai_id from imobdesk.ch_servicos s where s.id = t.servico_id
      union all select s.id, s.pai_id from imobdesk.ch_servicos s join cadeia c2 on s.id = c2.pai_id)
    select coalesce(array_agg(id::text), '{}') into v_atual from cadeia;
  elsif v_campo = 'categoria' then v_atual := array_remove(array[t.categoria_id::text], null);
  elsif v_campo = 'urgencia' then v_atual := array[t.urgencia_id::text];
  elsif v_campo = 'setor' then v_atual := array[t.setor_id::text];
  elsif v_campo = 'origem' then v_atual := array[t.origem];
  elsif v_campo like 'campo:%' then
    v_atual := case jsonb_typeof(t.campos -> substr(v_campo, 7))
                 when 'array' then array(select jsonb_array_elements_text(t.campos -> substr(v_campo, 7)))
                 when 'null' then '{}'
                 else array_remove(array[nullif(btrim(t.campos ->> substr(v_campo, 7)), '')], null) end;
  else
    return false;
  end if;
  return case v_op
    when 'um_de' then v_atual && v_valores
    when 'nao_um_de' then not (v_atual && v_valores)
    when 'preenchido' then cardinality(v_atual) > 0
    when 'vazio' then cardinality(v_atual) = 0
    else false end;
end;
$$;

/** Estado de cada campo adicional para este ticket: visível e obrigatório (regras de cima para baixo; a última vence). */
create or replace function imobdesk.ch_campos_estado(t imobdesk.ch_tickets)
returns table (chave text, visivel boolean, obrigatorio boolean)
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_vis jsonb := '{}';
  v_obr jsonb := '{}';
  c record;
  r record;
  a jsonb;
begin
  for c in select x.chave, x.obrigatorio from imobdesk.ch_campos x where x.ativo loop
    v_vis := v_vis || jsonb_build_object(c.chave, c.obrigatorio <> 'regra');
    v_obr := v_obr || jsonb_build_object(c.chave, c.obrigatorio = 'sempre');
  end loop;
  for r in select x.condicoes, x.acoes from imobdesk.ch_regras_exibicao x where x.ativa order by x.ordem, x.id loop
    if not exists (select 1 from jsonb_array_elements(r.condicoes) cc where not imobdesk.ch_regra_condicao(t, cc)) then
      for a in select * from jsonb_array_elements(r.acoes) loop
        continue when not (v_vis ? (a ->> 'campo'));
        if a ->> 'acao' = 'exibir' then v_vis := v_vis || jsonb_build_object(a ->> 'campo', true);
        elsif a ->> 'acao' = 'ocultar' then v_vis := v_vis || jsonb_build_object(a ->> 'campo', false); v_obr := v_obr || jsonb_build_object(a ->> 'campo', false);
        elsif a ->> 'acao' = 'obrigar' then v_vis := v_vis || jsonb_build_object(a ->> 'campo', true); v_obr := v_obr || jsonb_build_object(a ->> 'campo', true);
        elsif a ->> 'acao' = 'liberar' then v_obr := v_obr || jsonb_build_object(a ->> 'campo', false);
        end if;
      end loop;
    end if;
  end loop;
  return query select k, (v_vis ->> k)::boolean, (v_obr ->> k)::boolean from jsonb_object_keys(v_vis) k;
end;
$$;

/** Rótulos dos campos obrigatórios que estão vazios (bloqueiam resolver/fechar). */
create or replace function imobdesk.ch_campos_pendentes(t imobdesk.ch_tickets)
returns text[]
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(array_agg(c.rotulo order by c.ordem), '{}')
  from imobdesk.ch_campos_estado(t) e
  join imobdesk.ch_campos c on c.chave = e.chave
  where e.obrigatorio and e.visivel
    and (t.campos -> e.chave is null or jsonb_typeof(t.campos -> e.chave) = 'null'
         or btrim(t.campos ->> e.chave) = '' or (jsonb_typeof(t.campos -> e.chave) = 'array' and jsonb_array_length(t.campos -> e.chave) = 0));
$$;

-- ---------- Gatilhos: SLA, pausa, encerramento e histórico ----------
create or replace function imobdesk.ch_tickets_antes()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_cat text := (select s.categoria from imobdesk.ch_status s where s.id = new.status_id);
  v_cat_antes text;
  h record;
begin
  new.atualizado_em := now();
  if tg_op = 'UPDATE' then
    v_cat_antes := (select s.categoria from imobdesk.ch_status s where s.id = old.status_id);
  end if;
  -- Equipe: a do serviço; sem serviço, a padrão do setor.
  if new.equipe_id is null and (tg_op = 'INSERT' or new.servico_id is distinct from old.servico_id) then
    new.equipe_id := coalesce(imobdesk.ch_servico_equipe(new.servico_id), (select st.equipe_padrao_id from imobdesk.at_setores st where st.id = new.setor_id));
  end if;
  -- Prazos: na criação e quando muda serviço, urgência ou setor (se não foi alterado à mão).
  if not new.sla_manual and (tg_op = 'INSERT' or new.servico_id is distinct from old.servico_id or new.urgencia_id is distinct from old.urgencia_id or new.setor_id is distinct from old.setor_id) then
    select * into h from imobdesk.ch_sla_horas(new.servico_id, new.urgencia_id, new.setor_id);
    new.sla_resposta_ate := imobdesk.ch_somar_horas_uteis(new.setor_id, new.criado_em, h.resposta);
    new.sla_solucao_ate := imobdesk.ch_somar_horas_uteis(new.setor_id, new.criado_em, h.solucao);
  end if;
  -- Pausa nos pendentes (T9): ao sair, o prazo anda o tempo que ficou pausado.
  if v_cat = 'pendente' and new.sla_pausado_desde is null then
    new.sla_pausado_desde := now();
  elsif v_cat <> 'pendente' and new.sla_pausado_desde is not null then
    new.sla_solucao_ate := new.sla_solucao_ate + (now() - new.sla_pausado_desde);
    new.sla_pausado_desde := null;
  end if;
  -- Encerramento e reabertura.
  if v_cat in ('resolvido', 'fechado', 'cancelado') then
    if new.encerrado_em is null or tg_op = 'UPDATE' and v_cat_antes not in ('resolvido', 'fechado', 'cancelado') then
      new.encerrado_em := now();
    end if;
  else
    new.encerrado_em := null;
  end if;
  if v_cat = 'andamento' and new.assumido_em is null then new.assumido_em := now(); end if;
  -- Justificativa precisa ser do status.
  if new.justificativa_id is not null and not exists (select 1 from imobdesk.ch_status_justificativas j where j.id = new.justificativa_id and j.status_id = new.status_id) then
    new.justificativa_id := null;
  end if;
  return new;
end;
$$;

drop trigger if exists ch_tickets_antes on imobdesk.ch_tickets;
create trigger ch_tickets_antes before insert or update on imobdesk.ch_tickets
for each row execute function imobdesk.ch_tickets_antes();

/** Iniciais do avatar: primeira letra do primeiro e do último nome ("Ana Lima" → "AL"; "Wagner" → "W"). */
create or replace function imobdesk.ch_iniciais(p_nome text)
returns text
language sql
immutable
set search_path = ''
as $$
  select upper(left(btrim(p_nome), 1) ||
         case when array_length(regexp_split_to_array(btrim(p_nome), '\s+'), 1) > 1
              then left((regexp_split_to_array(btrim(p_nome), '\s+'))[array_length(regexp_split_to_array(btrim(p_nome), '\s+'), 1)], 1) else '' end);
$$;

