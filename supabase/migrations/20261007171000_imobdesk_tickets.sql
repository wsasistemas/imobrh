create or replace function imobdesk.ch_tickets_historico()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_autor uuid := (select auth.uid());
  v_nome text := imobdesk.ch_nome_usuario((select auth.uid()));
begin
  if tg_op = 'INSERT' then
    insert into imobdesk.ch_ticket_eventos (ticket_id, tipo, descricao, autor_id, autor_nome)
    values (new.id, 'criado', format('Ticket criado (%s)', new.origem), v_autor, v_nome);
    return null;
  end if;
  if new.status_id is distinct from old.status_id or new.justificativa_id is distinct from old.justificativa_id then
    insert into imobdesk.ch_ticket_eventos (ticket_id, tipo, descricao, de, para, autor_id, autor_nome)
    values (new.id, 'status', 'Status alterado',
            jsonb_build_object('statusId', old.status_id, 'justificativaId', old.justificativa_id), jsonb_build_object('statusId', new.status_id, 'justificativaId', new.justificativa_id), v_autor, v_nome);
  end if;
  if new.responsavel_id is distinct from old.responsavel_id then
    insert into imobdesk.ch_ticket_eventos (ticket_id, tipo, descricao, de, para, autor_id, autor_nome)
    values (new.id, 'responsavel', format('Responsável: %s', coalesce((select u.nome from imobdesk.usuarios u where u.id = new.responsavel_id), 'ninguém')),
            to_jsonb(old.responsavel_id), to_jsonb(new.responsavel_id), v_autor, v_nome);
  end if;
  if new.equipe_id is distinct from old.equipe_id then
    insert into imobdesk.ch_ticket_eventos (ticket_id, tipo, descricao, de, para, autor_id, autor_nome)
    values (new.id, 'equipe', format('Equipe: %s', coalesce((select e.nome from imobdesk.at_equipes e where e.id = new.equipe_id), 'sem equipe')), to_jsonb(old.equipe_id), to_jsonb(new.equipe_id), v_autor, v_nome);
  end if;
  if new.servico_id is distinct from old.servico_id then
    insert into imobdesk.ch_ticket_eventos (ticket_id, tipo, descricao, de, para, autor_id, autor_nome)
    values (new.id, 'servico', format('Serviço: %s', coalesce((select s.nome from imobdesk.ch_servicos s where s.id = new.servico_id), '—')), to_jsonb(old.servico_id), to_jsonb(new.servico_id), v_autor, v_nome);
  end if;
  if new.categoria_id is distinct from old.categoria_id then
    insert into imobdesk.ch_ticket_eventos (ticket_id, tipo, descricao, de, para, autor_id, autor_nome)
    values (new.id, 'categoria', format('Categoria: %s', coalesce((select c.nome from imobdesk.ch_categorias c where c.id = new.categoria_id), '—')), to_jsonb(old.categoria_id), to_jsonb(new.categoria_id), v_autor, v_nome);
  end if;
  if new.urgencia_id is distinct from old.urgencia_id then
    insert into imobdesk.ch_ticket_eventos (ticket_id, tipo, descricao, de, para, autor_id, autor_nome)
    values (new.id, 'urgencia', format('Urgência: %s', (select u.nome from imobdesk.ch_urgencias u where u.id = new.urgencia_id)), to_jsonb(old.urgencia_id), to_jsonb(new.urgencia_id), v_autor, v_nome);
  end if;
  if new.campos is distinct from old.campos then
    insert into imobdesk.ch_ticket_eventos (ticket_id, tipo, descricao, de, para, autor_id, autor_nome)
    values (new.id, 'campos', 'Campos adicionais alterados', old.campos, new.campos, v_autor, v_nome);
  end if;
  if new.tags is distinct from old.tags then
    insert into imobdesk.ch_ticket_eventos (ticket_id, tipo, descricao, de, para, autor_id, autor_nome)
    values (new.id, 'tags', 'Tags alteradas', to_jsonb(old.tags), to_jsonb(new.tags), v_autor, v_nome);
  end if;
  if new.sla_manual and (new.sla_solucao_ate is distinct from old.sla_solucao_ate) then
    insert into imobdesk.ch_ticket_eventos (ticket_id, tipo, descricao, de, para, autor_id, autor_nome)
    values (new.id, 'sla', 'Previsão de solução alterada à mão', to_jsonb(old.sla_solucao_ate), to_jsonb(new.sla_solucao_ate), v_autor, v_nome);
  end if;
  return null;
end;
$$;

