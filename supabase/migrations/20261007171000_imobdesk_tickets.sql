  f text;
begin
  foreach f in array array[
    'ch_somar_horas_uteis(bigint, timestamptz, numeric)', 'ch_sla_horas(bigint, bigint, bigint)', 'ch_servico_equipe(bigint)',
    'ch_pode_ver_ticket(bigint, bigint, uuid)', 'ch_ticket_visivel(bigint)', 'ch_regra_condicao(imobdesk.ch_tickets, jsonb)',
    'ch_campos_estado(imobdesk.ch_tickets)', 'ch_campos_pendentes(imobdesk.ch_tickets)', 'ch_nome_usuario(uuid)', 'ch_iniciais(text)',
    'ch_ticket_criar(jsonb)', 'ch_ticket_atualizar(bigint, jsonb)', 'ch_ticket_acao(bigint, jsonb)', 'ch_ticket_detalhe(bigint)', 'ch_ticket_seguir(bigint, boolean)',
    'ch_ticket_clonar(bigint, jsonb)', 'ch_ticket_mesclar(bigint, bigint)', 'ch_ticket_excluir(bigint)', 'ch_painel()'
  ] loop
