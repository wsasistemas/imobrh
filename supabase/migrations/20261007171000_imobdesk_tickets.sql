-- Ticket único (docs/PLANO-tickets-unificados.md, aprovado em 07/10/2026): ch_tickets é a fonte única dos
-- tickets de todos os canais. Ações (conversa), eventos (histórico), seguidores, prazo de SLA em horas úteis
-- pelo horário do setor (D6), pausa nos status pendentes (T9), visibilidade (D7), regras para exibição e
-- obrigatórios conferidos no banco (cadastros D7) e as RPCs que as telas usam. Só aditiva.

-- ---------- Tabelas ----------
create table if not exists imobdesk.ch_tickets (
  id                    bigint      generated by default as identity (start with 1000) primary key,
  assunto               text        not null check (length(btrim(assunto)) between 1 and 300),
  origem                text        not null check (origem in ('email', 'whatsapp', 'intranet', 'agente')),
  recebido_em           text        not null default 'Agente' check (length(recebido_em) <= 160),  -- conta, número ou "Intranet"/"Agente"
  solicitante_pessoa_id bigint      references imobdesk.at_pessoas (id) on delete set null,
  solicitante_nome      text        not null check (length(btrim(solicitante_nome)) between 1 and 160),
  solicitante_contato   text        check (length(solicitante_contato) <= 160),                    -- e-mail ou telefone de retorno
  email_conta_id        bigint      references imobdesk.at_email_contas (id) on delete set null,
  email_thread_id       text,                                                                         -- Message-ID raiz da conversa
  numero_id             bigint      references imobdesk.at_numeros (id) on delete set null,
  conversa_id           bigint      references imobdesk.at_conversas (id) on delete set null,
  setor_id              bigint      not null references imobdesk.at_setores (id),
  equipe_id             bigint      references imobdesk.at_equipes (id) on delete set null,
  responsavel_id        uuid        references imobdesk.usuarios (id) on delete set null,
  servico_id            bigint      references imobdesk.ch_servicos (id),
  categoria_id          bigint      references imobdesk.ch_categorias (id),
  urgencia_id           bigint      not null references imobdesk.ch_urgencias (id),
  status_id             bigint      not null references imobdesk.ch_status (id),
  justificativa_id      bigint      references imobdesk.ch_status_justificativas (id),
  tags                  text[]      not null default '{}',
  cc                    text[]      not null default '{}',
  campos                jsonb       not null default '{}',                                            -- valores dos campos adicionais, por chave
  solucao_aplicada      text        check (length(solucao_aplicada) <= 20000),
  criado_em             timestamptz not null default now(),
  criado_por            uuid,
  assumido_em           timestamptz,
  primeira_resposta_em  timestamptz,
  sla_resposta_ate      timestamptz,
  sla_solucao_ate       timestamptz,
  sla_manual            boolean     not null default false,                                           -- prazo alterado à mão (T9)
  sla_pausado_desde     timestamptz,
  encerrado_em          timestamptz,                                                                  -- resolvido, fechado ou cancelado
  mesclado_em_id        bigint      references imobdesk.ch_tickets (id),
  clonado_de_id         bigint      references imobdesk.ch_tickets (id),
  excluido_em           timestamptz,
  excluido_por          uuid,
  atualizado_em         timestamptz not null default now()
);
create index if not exists ch_tickets_setor_idx on imobdesk.ch_tickets (setor_id, encerrado_em);
create index if not exists ch_tickets_equipe_idx on imobdesk.ch_tickets (equipe_id);
create index if not exists ch_tickets_resp_idx on imobdesk.ch_tickets (responsavel_id);
create index if not exists ch_tickets_conversa_idx on imobdesk.ch_tickets (conversa_id);
create index if not exists ch_tickets_thread_idx on imobdesk.ch_tickets (email_thread_id);

create table if not exists imobdesk.ch_ticket_acoes (
